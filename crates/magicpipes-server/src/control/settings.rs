//! What administrators change on the Settings page while the server runs: OpenID Connect
//! providers, who a first sign-in may create an account for, the mail server, and their own
//! certificates (which `certs::provided` keeps, as files).
//!
//! The configuration file stays read-only and holds everything needed before the database opens.
//! These settings live in the database, and what's in effect is the two together: a provider or mail
//! server in the file wins over one on the page, and is locked there. Client secrets are files in
//! `<data_dir>/oidc-secrets/` (like the file's own `client_secret_file`) and the mail server's
//! password is `<data_dir>/smtp-password`, so neither the database nor the generated configuration
//! holds one.
//!
//! [`GENERATED_CONFIG`] is a copy of the settings in effect, written at startup and after every
//! change. Nothing reads it back, so it can't disagree with what the server does.

